#!/usr/bin/env bash
set -euo pipefail

prefix="ARCH"
out="${1:-$HOME/system-inventory/gnome-analysis-$(date +%F-%H%M%S)}"

if command -v chezmoi >/dev/null 2>&1; then
  distro="$(chezmoi execute-template '{{ .distro }}' 2>/dev/null || true)"
  case "${distro,,}" in
    cachyos) prefix="CACHYOS" ;;
    arch|archlinux|"") prefix="ARCH" ;;
  esac
fi

mkdir -p "$out"

pacman -Sgq gnome | sort -u > "$out/gnome-group-repo.txt"
pacman -Qq | sort -u > "$out/pacman-installed-all.txt"
pacman -Qqen | sort -u > "$out/pacman-explicit-native.txt"
pacman -Qqem 2>/dev/null | sort -u > "$out/pacman-explicit-aur.txt" || true   # exit 1 when there are no AUR packages

# GNOME group packages currently installed after your cleanup.
comm -12 "$out/gnome-group-repo.txt" "$out/pacman-installed-all.txt" > "$out/gnome-group-installed-now.txt"

# If future setup installs the full `gnome` group, removing this list should reproduce
# the current cleaned GNOME group state, assuming the group does not change dramatically.
comm -23 "$out/gnome-group-repo.txt" "$out/gnome-group-installed-now.txt" > "$out/gnome-remove-after-full-group-install.txt"

comm -12 "$out/gnome-group-installed-now.txt" "$out/pacman-explicit-native.txt" > "$out/gnome-group-explicit-native-now.txt"

# Package-installed GNOME extensions only. User-installed extensions via Extension Manager
# are recorded separately and should not be put into pacman/paru arrays.
grep -E '^(gnome-shell-extension|gnome-browser-connector)' "$out/pacman-explicit-native.txt" > "$out/gnome-extension-packages-native.txt" || true
grep -E '^gnome-shell-extension' "$out/pacman-explicit-aur.txt" > "$out/gnome-extension-packages-aur.txt" || true

if command -v gnome-extensions >/dev/null 2>&1; then
  gnome-extensions list > "$out/gnome-extensions-all.txt" || true
  gnome-extensions list --enabled > "$out/gnome-extensions-enabled.txt" || true
  gnome-extensions list --disabled > "$out/gnome-extensions-disabled.txt" || true
fi

find "$HOME/.local/share/gnome-shell/extensions" -maxdepth 1 -mindepth 1 -type d -printf '%f\n' 2>/dev/null | sort -u > "$out/gnome-extensions-user-installed.txt" || true
find /usr/share/gnome-shell/extensions -maxdepth 1 -mindepth 1 -type d -printf '%f\n' 2>/dev/null | sort -u > "$out/gnome-extensions-system-installed.txt" || true

if command -v dconf >/dev/null 2>&1; then
  dconf dump /org/gnome/shell/extensions/ > "$out/org-gnome-shell-extensions.ini" || true
  dconf dump /org/gnome/shell/ > "$out/org-gnome-shell.ini" || true
fi

if command -v flatpak >/dev/null 2>&1; then
  flatpak list --app --columns=application,name,installation > "$out/flatpak-apps.tsv" || true
  flatpak list --app --columns=application > "$out/flatpak-app-ids.txt" || true
fi

array_from_file() {
  local name="$1" file="$2"
  echo "$name=("
  if [[ -s "$file" ]]; then
    sed 's/^/  /' "$file"
  fi
  echo ")"
  echo
}

{
  echo "# Generated by gnome-analyze.sh on $(date -Iseconds)"
  echo "# Review before pasting into private_dot_config/ucli/packages.bash."
  echo
  array_from_file "${prefix}_GNOME_REMOVE" "$out/gnome-remove-after-full-group-install.txt"
  array_from_file "${prefix}_GNOME_EXTENSION_PACKAGES" "$out/gnome-extension-packages-native.txt"
  array_from_file "${prefix}_GNOME_EXTENSION_AUR" "$out/gnome-extension-packages-aur.txt"
} > "$out/packages-bash-gnome-snippet.bash"

echo "$out"
if command -v tree >/dev/null 2>&1; then
  tree "$out"
fi

echo
echo "Important files:"
echo "  $out/gnome-group-installed-now.txt"
echo "  $out/gnome-remove-after-full-group-install.txt"
echo "  $out/packages-bash-gnome-snippet.bash"
echo "  $out/gnome-extensions-enabled.txt"
echo "  $out/org-gnome-shell-extensions.ini"
echo "  $out/flatpak-app-ids.txt"
